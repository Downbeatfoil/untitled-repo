/** Lane: export. Cheat-sheet markdown + share text. */
import type { CoursePack } from "@/shared/contract";

export function packToMarkdown(pack: CoursePack): string {
  const label = new Map(pack.concepts.map((c) => [c.id, c.label]));
  const topics = [...pack.examTopics].sort((a, b) => b.frequency - a.frequency);
  return [
    `# ${pack.course.code}: ${pack.course.title}`,
    "",
    pack.summary,
    "",
    `**Fear score:** ${pack.fearScore}/100`,
    "",
    "## What's on the exam",
    ...topics.map((t) => `- ${label.get(t.conceptId) ?? t.conceptId}: ${Math.round(t.frequency * 100)}%`),
    "",
    "## Concepts",
    ...pack.concepts.map((c) => `- **${c.label}**: ${c.description}`),
    "",
    "## Tips",
    ...pack.tips.map((t) => `- ${t}`),
    "",
    "## Sources",
    ...pack.sources.map((s) => `- [${s.title}](${s.url}) (${s.kind})`),
    "",
    "_Generated by SmartPath Scout with Grok._",
  ].join("\n");
}

export function shareText(pack: CoursePack): string {
  const hardest = [...pack.difficulty].sort((a, b) => b.score - a.score)[0];
  const hardLabel = pack.concepts.find((c) => c.id === hardest?.conceptId)?.label ?? "the exams";
  return `I scouted ${pack.course.code} with Grok: fear score ${pack.fearScore}/100, ${pack.sources.length} sources, and the hardest topic is ${hardLabel}. Built with SmartPath Scout.`;
}
